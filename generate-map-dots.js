#!/usr/bin/env node

/**
 * Read the dotted world map in assets/world-dots.png (white dots on a dark ground) and write each dot's centre
 * to src/lib/mapDots.ts, in the PNG's own pixel coordinates. The About page's event map draws those dots.
 * To change dot density or coverage, edit/replace the PNG and re-run (`pnpm map-dots`). Dot size is set in
 * EventMapTile.svelte, not here. Needs ImageMagick 7.
 */

import { execFile } from 'child_process';
import { promisify } from 'util';
import { writeFile } from 'fs/promises';
import path from 'path';
import { fileURLToPath } from 'url';

const execFileAsync = promisify(execFile);
const ROOT_DIR = path.dirname(fileURLToPath(import.meta.url));
const SOURCE_PNG = path.join(ROOT_DIR, 'assets', 'world-dots.png');
const OUTPUT_FILE = path.join(ROOT_DIR, 'src', 'lib', 'mapDots.ts');
// Anything wider than this is the background or an artefact, not a dot.
const MAX_DOT_SIZE_PX = 40;

// One line per connected blob, e.g. "  182: 7x8+1386+92 1389.1,95.4 44 graya(255,1490.43)"
const COMPONENT_LINE = /^\s*\d+: (\d+)x(\d+)\+\d+\+\d+ ([\d.]+),([\d.]+) \d+ (\S+)/;

async function listConnectedComponents(pngPath) {
	try {
		const { stdout } = await execFileAsync(
			'magick',
			[
				pngPath,
				'-colorspace',
				'gray',
				'-threshold',
				'50%',
				'-define',
				'connected-components:verbose=true',
				'-connected-components',
				'8',
				'null:'
			],
			{ maxBuffer: 16 * 1024 * 1024 }
		);
		return stdout;
	} catch (error) {
		throw new Error(
			`ImageMagick failed on ${pngPath} (${error.message}). Install ImageMagick 7 (\`brew install imagemagick\`) and check the file exists.`
		);
	}
}

function parseDotCentres(componentListing) {
	const dots = [];
	for (const line of componentListing.split('\n')) {
		const match = COMPONENT_LINE.exec(line);
		if (!match) continue;
		const [, width, height, centreX, centreY, colour] = match;
		const isWhite = colour.startsWith('gray(255') || colour.startsWith('graya(255');
		if (!isWhite || Number(width) > MAX_DOT_SIZE_PX || Number(height) > MAX_DOT_SIZE_PX) continue;
		dots.push([Number(centreX), Number(centreY)]);
	}
	// Row by row, left to right, so the output diffs cleanly when the PNG changes.
	return dots.sort((first, second) => first[1] - second[1] || first[0] - second[0]);
}

async function readImageSize(pngPath) {
	const { stdout } = await execFileAsync('magick', ['identify', '-format', '%w %h', pngPath]);
	const [width, height] = stdout.trim().split(' ').map(Number);
	return { width, height };
}

function renderModule(dots, imageSize) {
	const rows = dots.map(([x, y]) => `[${x}, ${y}]`).join(', ');
	return `// GENERATED by generate-map-dots.js from assets/world-dots.png. Do not edit by hand; run \`pnpm map-dots\`.
// Dot centres in the PNG's pixel space (${imageSize.width}×${imageSize.height}); eventMap.ts projects cities into the same space.
export const MAP_IMAGE_SIZE = { width: ${imageSize.width}, height: ${imageSize.height} } as const;

export const MAP_DOTS: ReadonlyArray<readonly [number, number]> = [${rows}];
`;
}

const dots = parseDotCentres(await listConnectedComponents(SOURCE_PNG));
if (dots.length === 0) {
	throw new Error(
		`No white dots found in ${SOURCE_PNG}. The map should be light dots on a dark background.`
	);
}
await writeFile(OUTPUT_FILE, renderModule(dots, await readImageSize(SOURCE_PNG)));
console.log(`Wrote ${dots.length} dots to ${path.relative(ROOT_DIR, OUTPUT_FILE)}`);
